"""Compile the reviewed M0 dictionary into one transactional PostgreSQL migration.
Human semantic checks below supplement, never silently interpret, prose constraints.
"""
from pathlib import Path
import json
BASE = Path(__file__).resolve().parents[1]
OUT = BASE / 'm0-20260921'
D = json.loads((BASE / '数据库设计方案_V2.0清单.json').read_text(encoding='utf-8'))
TABLES = [t for t in D['tables'] if t['phase'] == 'M0 CRUD']

def q(s): return '"' + s.replace('"', '""') + '"'
def lit(s): return "'" + str(s).replace("'", "''") + "'"
def cols(s): return ', '.join(map(q, s))
def check_enum(field, vals): return f'{q(field)} IN ({", ".join(lit(v) for v in vals)})'
checks = {
'app_users': [check_enum('state',['active','disabled'])],
'project_members': [check_enum('state',['active','disabled'])],
'artifact_types': [check_enum('code',['PRD','UC','FR','FR_ALLOCATION'])],
'artifacts': [check_enum('type_code',['PRD','UC','FR','FR_ALLOCATION'])],
'artifact_revisions': [check_enum('created_via',['manual','import','migration'])],
'subsystem_design_versions': [check_enum('created_via',['manual','import','ai','copy'])],
'uc_scenario_items': ["(kind='branch' AND category IN ('a1','a2','a3','a4')) OR (kind='exception' AND category IN ('vehicle_state','mechanical','environmental','misuse','power'))"],
'permission_definitions': [check_enum('resource_kind',['project','function','PRD','UC','FR','FR_ALLOCATION','subsystem_design','view']), check_enum('action',['enter','open','read','create','update','generate','expand','accept','archive','export','manage_access','import']), "cardinality(allowed_scopes)>0 AND array_position(allowed_scopes,NULL) IS NULL AND allowed_scopes <@ ARRAY['project','function','artifact']::text[]"],
'access_bindings': ["(scope_kind='project' AND function_id IS NULL AND artifact_id IS NULL) OR (scope_kind='function' AND function_id IS NOT NULL AND artifact_id IS NULL) OR (scope_kind='artifact' AND function_id IS NOT NULL AND artifact_id IS NOT NULL)","scope_kind='project'"],
'security_audit_events': ["(scope_kind IS NULL AND project_id IS NULL AND function_id IS NULL AND artifact_id IS NULL) OR (scope_kind='project' AND project_id IS NOT NULL AND function_id IS NULL AND artifact_id IS NULL) OR (scope_kind='function' AND project_id IS NOT NULL AND function_id IS NOT NULL AND artifact_id IS NULL) OR (scope_kind='artifact' AND project_id IS NOT NULL AND function_id IS NOT NULL AND artifact_id IS NOT NULL)"],
'review_events': [check_enum('decision',['accept','reject','withdraw'])],
}
fixed={'prds':'PRD','prd_versions':'PRD','use_cases':'UC','uc_versions':'UC','functional_requirements':'FR','fr_versions':'FR','fr_allocations':'FR_ALLOCATION','allocation_versions':'FR_ALLOCATION'}
for name,typ in fixed.items(): checks[name]=[f'type_code={lit(typ)}']
lines=['-- Generated by tools/build_m0_migration.py; inspect before execution.',
       '-- 29 business tables only. M1 AI and its columns/keys are excluded.',
       '-- Transaction, target identity, advisory lock, migration ledger: managed by server_step.py.',
       'CREATE SCHEMA ee AUTHORIZATION ee_m0_owner;',
       'SET LOCAL ROLE ee_m0_owner;',
       'SET LOCAL search_path = ee, pg_catalog;',
       'REVOKE ALL ON SCHEMA ee FROM PUBLIC;']
for t in TABLES:
    fields=[f for f in t['fields'] if f['name']!='ai_run_id']
    parts=[]
    for f in fields:
        item=q(f['name'])+' '+f['type']+(' NOT NULL' if f['nullable']=='否' else '')
        default=f['default']
        if default!='—':
            if default=='{}': default="'{}'::jsonb"
            elif f['type']=='text': default=lit(default)
            item+=' DEFAULT '+default
        parts.append(item)
    parts.append('CONSTRAINT '+q(t['name']+'_pk')+' PRIMARY KEY ('+cols(t['pk'])+')')
    for i,key in enumerate(t['unique']):
        if 'ai_run_id' not in key:
            parts.append(f'CONSTRAINT {q(t["name"]+"_uq_"+str(i))} UNIQUE ({cols(key)})')
    cs=list(checks.get(t['name'],[]))
    for f in fields:
        n=f['name']
        if n in ['revision_no','version_no','event_no']: cs.append(q(n)+'>0')
        if n in ['lock_version','position','sort_order']: cs.append(q(n)+'>=0')
        if f['type']=='jsonb':
            shape='array' if n=='field_catalog' else 'object'
            cs.append((f'{q(n)} IS NULL OR ' if f['nullable']=='是' else '')+f'jsonb_typeof({q(n)})={lit(shape)}')
        if n in ['code','name','external_subject','display_name','workspace_key','request_key','event_type']:
            cs.append(f'length(btrim({q(n)}))>0')
    for i,c in enumerate(cs): parts.append(f'CONSTRAINT {q(t["name"]+"_ck_"+str(i))} CHECK (({c}) IS TRUE)')
    lines.append('CREATE TABLE ee.'+q(t['name'])+' (\n  '+',\n  '.join(parts)+'\n);')
    lines.append('COMMENT ON TABLE ee.'+q(t['name'])+' IS '+lit(t['purpose'])+';')
    for f in fields: lines.append('COMMENT ON COLUMN ee.'+q(t['name'])+'.'+q(f['name'])+' IS '+lit(f['purpose'])+';')
# All parent PK/UQ exist before any FK, including circular pointers.
for t in TABLES:
    for i,f in enumerate(t['foreign_keys']):
        if f['phase']!='M0 CRUD' or 'ai_run_id' in f['columns']:continue
        deferred=any(c in ['head_revision_id','accepted_revision_id','current_version_id'] for c in f['columns'])
        lines.append(f'ALTER TABLE ee.{q(t["name"])} ADD CONSTRAINT {q(t["name"]+"_fk_"+str(i))} FOREIGN KEY ({cols(f["columns"])}) REFERENCES ee.{q(f["parent"])} ({cols(f["references"])}) ON DELETE NO ACTION'+(' DEFERRABLE INITIALLY DEFERRED' if deferred else '')+';')
        # Exact FK-leading indexes; duplicates of existing PK/UQ prefixes skipped.
        keys=[t['pk']]+t['unique']
        if not any(k[:len(f['columns'])]==f['columns'] for k in keys):
            lines.append(f'CREATE INDEX {q(t["name"]+"_fkidx_"+str(i))} ON ee.{q(t["name"])} ({cols(f["columns"])});')
lines += ["CREATE UNIQUE INDEX artifacts_one_prd_per_function ON ee.artifacts(project_id,function_id) WHERE type_code='PRD';",
"CREATE UNIQUE INDEX access_bindings_project_uq ON ee.access_bindings(project_id,user_id) WHERE scope_kind='project';",
"CREATE UNIQUE INDEX access_bindings_function_uq ON ee.access_bindings(project_id,user_id,function_id) WHERE scope_kind='function';",
"CREATE UNIQUE INDEX access_bindings_artifact_uq ON ee.access_bindings(project_id,user_id,function_id,artifact_id) WHERE scope_kind='artifact';"]
lines.append((OUT/'integrity.sql.inc').read_text(encoding='utf-8'))
# No app login/DML grant in this phase; no unauthenticated API bypass.
lines += ['REVOKE ALL ON ALL TABLES IN SCHEMA ee FROM PUBLIC;',
          'REVOKE ALL ON ALL FUNCTIONS IN SCHEMA ee FROM PUBLIC;',
          'ALTER DEFAULT PRIVILEGES FOR ROLE ee_m0_owner IN SCHEMA ee REVOKE ALL ON TABLES FROM PUBLIC;',
          'ALTER DEFAULT PRIVILEGES FOR ROLE ee_m0_owner IN SCHEMA ee REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;',
          'RESET ROLE;']
OUT.mkdir(exist_ok=True)
(OUT/'001_m0_schema.sql').write_text('\n\n'.join(lines)+'\n',encoding='utf-8')
print('Compiled',len(TABLES),'tables')
